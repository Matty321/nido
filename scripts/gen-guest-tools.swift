// Generates Sources/NidoCore/Provisioning/GuestToolsPayload.swift from guest/linux/.
//
// Usage: swift scripts/gen-guest-tools.swift <guest/linux> <GuestToolsPayload.swift>
// Embeds the runtime files only: nido_guest_tools/*.py, bin/nido-guest-tools, bin/nido-ai-bridge,
// bin/nido-provision, ollama/ollama.service, ollama/release.json and VERSION (under
// /opt/nido-guest-tools/) and the Guest Tools systemd units nido-guest-tools.service and
// nido-ai-bridge.service (/etc/systemd/system/). The Ollama unit stays under /opt (phase 2:
// `nido-provision ollama-install` installs and enables it). Never tests/, reference/ or the README. The output is deterministic (files sorted by install path).

import Foundation

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data((message + "\n").utf8))
    exit(2)
}

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    fail("usage: swift scripts/gen-guest-tools.swift <guest/linux> <GuestToolsPayload.swift>")
}
let root = URL(fileURLWithPath: arguments[1], isDirectory: true)
let outputPath = arguments[2]
let fm = FileManager.default

struct Entry {
    let path: String
    let mode: String
    let data: Data
}

func read(_ relative: String) -> Data {
    guard let data = fm.contents(atPath: root.appendingPathComponent(relative).path) else {
        fail("can’t read \(relative) in \(root.path)")
    }
    return data
}

var entries: [Entry] = []
let moduleDirectory = root.appendingPathComponent("nido_guest_tools").path
guard let names = try? fm.contentsOfDirectory(atPath: moduleDirectory) else {
    fail("missing \(moduleDirectory)")
}
for name in names.filter({ $0.hasSuffix(".py") }) {
    entries.append(Entry(path: "/opt/nido-guest-tools/nido_guest_tools/\(name)", mode: "0644", data: read("nido_guest_tools/\(name)")))
}
entries.append(Entry(path: "/opt/nido-guest-tools/bin/nido-guest-tools", mode: "0755", data: read("bin/nido-guest-tools")))
entries.append(Entry(path: "/opt/nido-guest-tools/bin/nido-ai-bridge", mode: "0755", data: read("bin/nido-ai-bridge")))
entries.append(Entry(path: "/opt/nido-guest-tools/bin/nido-provision", mode: "0755", data: read("bin/nido-provision")))
for name in ["ollama.service", "release.json"] {
    entries.append(Entry(path: "/opt/nido-guest-tools/ollama/\(name)", mode: "0644", data: read("ollama/\(name)")))
}
entries.append(Entry(path: "/opt/nido-guest-tools/VERSION", mode: "0644", data: read("VERSION")))
for unit in ["nido-guest-tools.service", "nido-ai-bridge.service"] {
    entries.append(Entry(path: "/etc/systemd/system/\(unit)", mode: "0644", data: read("systemd/\(unit)")))
}
entries.sort { $0.path < $1.path }

guard let versionText = String(data: read("VERSION"), encoding: .utf8) else { fail("VERSION is not UTF-8") }
let version = versionText.trimmingCharacters(in: .whitespacesAndNewlines)
guard version.range(of: #"^[0-9]+\.[0-9]+\.[0-9]+$"#, options: .regularExpression) != nil else {
    fail("invalid VERSION: \(version)")
}

var out = """
    // SPDX-License-Identifier: Apache-2.0
    // Generated by scripts/gen-guest-tools.swift from guest/linux/. Never edit by hand:
    // change the sources and run `swift scripts/gen-guest-tools.swift guest/linux Sources/NidoCore/Provisioning/GuestToolsPayload.swift`.

    /// The Nido Guest Tools files cloud-init writes into a new guest (and the SSH installer copies
    /// into an existing one), as base64.
    public enum GuestToolsPayload {
        public static let version = "\(version)"

        public static let files: [(path: String, mode: String, base64: String)] = [

    """
for entry in entries {
    out += "        (path: \"\(entry.path)\", mode: \"\(entry.mode)\", base64: \"\(entry.data.base64EncodedString())\"),\n"
}
out += "    ]\n}\n"

do {
    try out.write(toFile: outputPath, atomically: true, encoding: .utf8)
} catch {
    fail("can’t write \(outputPath): \(error.localizedDescription)")
}
